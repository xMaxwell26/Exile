-- Run this in Supabase SQL Editor before enabling Online / SQL.
-- These tables support login validation, sanctions, player-count reporting,
-- and the no-reward vote callback. Player save files remain server-local.
CREATE TABLE IF NOT EXISTS connection_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(64) NOT NULL,
  host_address VARCHAR(128) NOT NULL,
  host_name VARCHAR(255) NOT NULL,
  client_hash BIGINT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS sanctions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(64),
  ipaddress VARCHAR(128),
  type VARCHAR(16) NOT NULL,
  expire TIMESTAMPTZ,
  closed INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS playersonline (
  id INTEGER PRIMARY KEY DEFAULT 1,
  currentlyOnline INTEGER NOT NULL DEFAULT 0
);
INSERT INTO playersonline (id, currentlyOnline) VALUES (1, 0) ON CONFLICT (id) DO NOTHING;
CREATE TABLE IF NOT EXISTS exile_votes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  player_name VARCHAR(12) NOT NULL,
  site VARCHAR(64) NOT NULL,
  external_id VARCHAR(128) NOT NULL,
  payload JSONB NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  last_seen_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (site, external_id)
);
